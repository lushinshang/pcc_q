export const ORG_LABELS = ORG_MATCH_GROUPS.map(([label]) => label) as [
  string,
  ...string[],
];

export const DEFAULT_ORG_LABEL = "國防部" as const;

export function resolveOrgLabel(rawOrgName: string): string | null {
  const normalized = rawOrgName.normalize("NFKC").trim();
  if (!normalized) return null;
  for (const [label, patterns] of ORG_MATCH_GROUPS) {
    if (patterns.some((pattern) => normalized.includes(pattern))) {
      return label;
    }
  }
  return null;
}
